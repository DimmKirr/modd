"""Generate the weather colour/name header: WMO code -> RGB565 colour and condition name.

The condition artwork lives in gen_weather_art.py, which emits the pixel-art sprites.

Usage:
  python3 tools/codegen/gen_ui_weather.py colors  > firmware/src/ui/themes/felucca/weather_colors.h
"""
import sys
import datetime


# ── RGB565 helpers ──────────────────────────────────────────────────────────

def rgb_to_565(r, g, b):
    """Convert 8-bit RGB to RGB565 (5R-6G-5B)."""
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


# ── Color palette ──────────────────────────────────────────────────────────

CATEGORIES = {
    "CLEAR":    (30,  120, 220),
    "PARTLY":   (70,  140, 200),
    "OVERCAST": (100, 110, 125),
    "FOG":      (130, 135, 145),
    "DRIZZLE":  (80,  105, 140),
    "RAIN":     (55,  75,  120),
    "SNOW":     (110, 130, 160),
    "SHOWERS":  (60,  85,  130),
    "THUNDER":  (50,  45,  80),
}

FG_WHITE = rgb_to_565(255, 255, 255)
FG_DIM   = rgb_to_565(200, 210, 220)


# ── WMO code tables ──────────────────────────────────────────────────────
# (wmo_code, color_category, glyph_key, human_name)

WMO_CODES = [
    (0,  "CLEAR",    "SUN",           "CLEAR SKY"),
    (1,  "CLEAR",    "SUN",           "MAINLY CLEAR"),
    (2,  "PARTLY",   "PARTIAL_CLOUD", "PARTLY CLOUDY"),
    (3,  "OVERCAST", "CLOUD",         "OVERCAST"),
    (45, "FOG",      "CLOUD",         "FOG"),
    (48, "FOG",      "CLOUD",         "DEPOSITING RIME FOG"),
    (51, "DRIZZLE",  "DRIZZLE",       "LIGHT DRIZZLE"),
    (53, "DRIZZLE",  "DRIZZLE",       "MODERATE DRIZZLE"),
    (55, "DRIZZLE",  "DRIZZLE",       "DENSE DRIZZLE"),
    (56, "DRIZZLE",  "DRIZZLE",       "LIGHT FREEZING DRIZZLE"),
    (57, "DRIZZLE",  "DRIZZLE",       "DENSE FREEZING DRIZZLE"),
    (61, "RAIN",     "RAIN",          "SLIGHT RAIN"),
    (63, "RAIN",     "RAIN",          "MODERATE RAIN"),
    (65, "RAIN",     "RAIN",          "HEAVY RAIN"),
    (66, "RAIN",     "RAIN",          "LIGHT FREEZING RAIN"),
    (67, "RAIN",     "RAIN",          "HEAVY FREEZING RAIN"),
    (71, "SNOW",     "SNOW",          "SLIGHT SNOWFALL"),
    (73, "SNOW",     "SNOW",          "MODERATE SNOWFALL"),
    (75, "SNOW",     "SNOW",          "HEAVY SNOWFALL"),
    (77, "SNOW",     "SNOW",          "SNOW GRAINS"),
    (80, "SHOWERS",  "RAIN",          "SLIGHT RAIN SHOWERS"),
    (81, "SHOWERS",  "RAIN",          "MODERATE RAIN SHOWERS"),
    (82, "SHOWERS",  "RAIN",          "VIOLENT RAIN SHOWERS"),
    (85, "SNOW",     "SNOW",          "SLIGHT SNOW SHOWERS"),
    (86, "SNOW",     "SNOW",          "HEAVY SNOW SHOWERS"),
    (95, "THUNDER",  "THUNDER",       "THUNDERSTORM"),
    (96, "THUNDER",  "THUNDER",       "THUNDERSTORM WITH SLIGHT HAIL"),
    (99, "THUNDER",  "THUNDER",       "THUNDERSTORM WITH HEAVY HAIL"),
]


# ── Glyph ASCII art (32x32, # = on, . = off) ───────────────────────────

def generate_colors():
    cat_colors = {k: rgb_to_565(*v) for k, v in CATEGORIES.items()}
    today = datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d')

    lines = []
    lines.append("/* SPDX-License-Identifier: GPL-3.0-only */")
    lines.append("/* AUTO-GENERATED by tools/codegen/gen_ui_weather.py colors -- DO NOT EDIT */")
    lines.append(f"/* Generated {today} */")
    lines.append("")
    lines.append("#ifndef WEATHER_COLORS_H")
    lines.append("#define WEATHER_COLORS_H")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append(f"#define WTHR_FG      0x{FG_WHITE:04X}  /* white */")
    lines.append(f"#define WTHR_FG_DIM  0x{FG_DIM:04X}  /* dim white */")
    lines.append("")
    lines.append("/* Background color categories (RGB565) */")
    for name, rgb in CATEGORIES.items():
        val = cat_colors[name]
        lines.append(f"#define WTHR_BG_{name:8s} 0x{val:04X}"
                     f"  /* ({rgb[0]:3d},{rgb[1]:3d},{rgb[2]:3d}) */")
    lines.append("")
    lines.append("static uint16_t weather_color(uint8_t wmo_code) {")
    lines.append("    switch (wmo_code) {")
    for code, cat, _, _ in WMO_CODES:
        lines.append(f"    case {code:3d}: return WTHR_BG_{cat};")
    lines.append(f"    default:  return WTHR_BG_OVERCAST;")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    lines.append("static const char *weather_condition_name(uint8_t wmo_code) {")
    lines.append("    switch (wmo_code) {")
    for code, _, _, name in WMO_CODES:
        lines.append(f'    case {code:3d}: return "{name}";')
    lines.append('    default:  return "UNKNOWN";')
    lines.append("    }")
    lines.append("}")
    lines.append("")
    lines.append("#endif /* WEATHER_COLORS_H */")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    if len(sys.argv) < 2 or sys.argv[1] != "colors":
        sys.exit("Usage: gen_ui_weather.py colors")
    sys.stdout.write(generate_colors())
