"""Convert assets/logo-light.png to an RLE-compressed RGB565 C header for the boot screen.

The logo is rendered ink-on-cream at 240px wide, centered vertically on a 240x240
canvas filled with the FM-1 body cream. Output: build/gen/boot_logo.h

BOOT_BG must stay in step with the splash fill colour in
firmware/src/ui/themes/felucca/shell.c (fsh_splash_render).

RLE format: pairs of (count, rgb565_be). Count is 1 byte (1-255 repeats);
a zero count byte means end-of-row. One row = 240 pixels.
"""
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

# FM-1 body cream; matches BOOT_BG in shell.c and PAPER in the logo generator.
BOOT_BG = (0xE8, 0xE4, 0xDF)
# Per-channel tolerance for treating a pixel as background. Only catches the
# outermost antialias ring, which is already ~98% background.
BG_SNAP = 4


def rgb565_be(r, g, b):
    v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
    return struct.pack('>H', v)


def rle_row(pixels):
    out = bytearray()
    i = 0
    n = len(pixels)
    while i < n:
        val = pixels[i]
        run = 1
        while i + run < n and pixels[i + run] == val and run < 255:
            run += 1
        out.append(run)
        out.extend(val)
        i += run
    out.append(0)
    return bytes(out)


def convert(src, dst, width=240, canvas=240):
    try:
        from PIL import Image
    except ImportError:
        print('error: Pillow not installed (uv add pillow)', file=sys.stderr)
        raise SystemExit(1)

    img = Image.open(src).convert('RGBA')
    ratio = width / img.width
    h = int(img.height * ratio)
    img = img.resize((width, h), Image.LANCZOS)

    rows = []
    for y in range(h):
        row_px = []
        for x in range(width):
            r, g, b, a = img.getpixel((x, y))
            # Lanczos overshoots into a bright halo around the glyphs. Nothing in
            # the artwork is lighter than the background, so clamp per channel.
            r, g, b = (min(c, t) for c, t in zip((r, g, b), BOOT_BG))
            if a < 128 or max(t - c for c, t in zip((r, g, b), BOOT_BG)) <= BG_SNAP:
                # Snap the faint antialias remainder to the exact background, so it
                # cannot band against the lcd_fill and so runs stay long.
                row_px.append(rgb565_be(*BOOT_BG))
            else:
                row_px.append(rgb565_be(r, g, b))
        rows.append(row_px)

    y_off = (canvas - h) // 2

    rle_data = bytearray()
    for y in range(canvas):
        if y < y_off or y >= y_off + h:
            rle_data.extend(rle_row([rgb565_be(*BOOT_BG)] * width))
        else:
            rle_data.extend(rle_row(rows[y - y_off]))

    dst.parent.mkdir(parents=True, exist_ok=True)
    with open(dst, 'w') as f:
        f.write('/* generated by tools/logo_convert.py */\n')
        f.write(f'#define BOOT_LOGO_W {width}\n')
        f.write(f'#define BOOT_LOGO_H {canvas}\n')
        f.write(f'#define BOOT_LOGO_IMG_H {h}\n')
        f.write(f'#define BOOT_LOGO_Y_OFF {y_off}\n')
        # The splash fill and the version-text background must use this exact
        # value, or the bitmap edge shows as a seam against the screen.
        bg565 = struct.unpack('>H', rgb565_be(*BOOT_BG))[0]
        f.write(f'#define BOOT_LOGO_BG 0x{bg565:04X}  /* #{BOOT_BG[0]:02X}{BOOT_BG[1]:02X}{BOOT_BG[2]:02X} */\n')
        f.write(f'static const uint8_t boot_logo_rle[{len(rle_data)}] = {{\n')
        for i in range(0, len(rle_data), 16):
            chunk = rle_data[i:i+16]
            f.write('    ' + ','.join(f'0x{b:02X}' for b in chunk) + ',\n')
        f.write('};\n')

    print(f'logo: {src.name} -> {dst.relative_to(ROOT)} '
          f'({width}x{h} in {canvas}x{canvas}, {len(rle_data)} bytes RLE)')


if __name__ == '__main__':
    src = ROOT / 'assets' / 'logo-light.png'
    dst = ROOT / 'build' / 'gen' / 'boot_logo.h'
    convert(src, dst)
