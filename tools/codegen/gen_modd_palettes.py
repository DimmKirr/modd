"""The modd theme's palettes: Melodee's set plus two from the modd logo, through Melodee's generator.

  gen_modd_palettes.py OUT.h [--report]

MODD is the logo: cream #E8E4DF background, ink #202426 text, the O's orange #D94736 as the accent
family. MODD NIGHT inverts it. Melodee's contrast checks (gen_ui_palettes.py CHECKS) apply unchanged,
so the orange is shifted darker on cream and lighter on ink until every pairing clears 4.5:1; the
hue is the logo's. MODD is the default palette; the settings page offers the whole list.
"""
import importlib.util
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
UPSTREAM = ROOT / 'firmware' / 'upstream' / 'melodee' / 'tools' / 'gen_ui_palettes.py'

# name, bg, surf, text, accent, (track 1, 2, 3, 4)
MODD = [
    ("MODD",       (232, 228, 223), (221, 216, 209), (32, 36, 38),    (150, 40, 26),
     ((150, 40, 26), (104, 62, 0), (0, 84, 70), (64, 52, 160))),
    ("MODD NIGHT", (32, 36, 38),    (46, 51, 54),    (232, 228, 223), (248, 124, 100),
     ((248, 124, 100), (240, 190, 84), (84, 212, 176), (176, 168, 255))),
]


def load():
    spec = importlib.util.spec_from_file_location('melodee_palettes', UPSTREAM)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def main():
    mod = load()
    mod.PALETTES = mod.PALETTES + MODD
    mod.LINE_PCT = dict(mod.LINE_PCT, **{"MODD": 14, "MODD NIGHT": 12})
    default = mod.PALETTES.index(MODD[0])
    out = next((a for a in sys.argv[1:] if not a.startswith('--')), None)
    mod.main()                       # reads sys.argv; exits 1 on a contrast miss
    if out:
        p = Path(out)
        t = re.sub(r'#define UI_DEFAULT_INDEX \d+u', f'#define UI_DEFAULT_INDEX {default}u', p.read_text())
        t = t.replace('generated by tools/gen_ui_palettes.py', 'generated by tools/codegen/gen_modd_palettes.py (Melodee palettes + MODD)')
        p.write_text(t)


if __name__ == '__main__':
    main()
